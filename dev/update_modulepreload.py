# Re-generates the <link rel="modulepreload"> block in index.html from app.js's import graph.
# Run from the forge-deploy folder:  python dev/update_modulepreload.py
import re
seen = {}
def deps(f):
    if f in seen: return
    seen[f] = 1
    for m in re.finditer(r"from\s+['\"](\./[^'\"]+\.js)['\"]|import\s+['\"](\./[^'\"]+\.js)['\"]", open(f, encoding='utf-8').read()):
        deps(m.group(1) or m.group(2))
deps('./app.js')
mods = ['app.js'] + sorted(x[2:] for x in seen if x != './app.js')
block = '<!-- modulepreload:begin (generated by dev/update_modulepreload.py -- re-run it after adding or renaming a module) -->\n'
block += ''.join('<link rel="modulepreload" href="https://www.gstatic.com/firebasejs/10.12.2/%s" crossorigin>\n' % g for g in ['firebase-app.js', 'firebase-auth.js', 'firebase-firestore.js'])
block += ''.join('<link rel="modulepreload" href="%s">\n' % m for m in mods)
block += '<!-- modulepreload:end -->\n'
t = open('index.html', encoding='utf-8', newline='').read()
nl = '\r\n' if '\r\n' in t else '\n'
t = t.replace('\r\n', '\n')
t = re.sub(r'<!-- modulepreload:begin.*?<!-- modulepreload:end -->\n', lambda _: block, t, flags=re.S)
open('index.html', 'w', encoding='utf-8', newline='').write(t.replace('\n', nl))
print(len(mods), 'modules')
